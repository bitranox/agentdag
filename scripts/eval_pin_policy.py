"""Generate arm P's tier policy: every role pinned to one model row.

Round 1 of the `spec` probe could not separate decomposition from model tier. Its held-fixed
table said the worker tier was sonnet in both arms, and that was false when written: agentdag's
planner picks a `tier_role` per node and the shipped table maps each role to a different row, so
the coordinator arm ran fable, sonnet and opus against a control pinned to sonnet. Whatever the
two arms differed by, it was not only decomposition.

Arm P removes the axis. Pinning is generated from the shipped table rather than hand-edited, for
two reasons: a hand-edited copy has no provenance beyond someone's memory of what they changed,
and the shipped table's own instruction is that retiring a model means flipping `available`,
never deleting the row - which a person editing under time pressure is exactly who forgets.

Comments do not survive the round trip, which is why the output carries a generated header
naming its source and what was changed. It is a derived artefact, so it should not wear the
shipped table's commentary as if it were the shipped table.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any, cast

import yaml

__all__ = ["PinningError", "pin_policy"]

# Executors the kernel actually wires. A row naming anything else is refused at wiring time, so
# pinning every role onto one would produce a table that cannot start a run.
WIRED_EXECUTORS = frozenset({"claude"})

HEADER = """\
# GENERATED by scripts/eval_pin_policy.py - do not edit by hand.
#
# Source:  {source}
# Change:  every model row except '{alias}' set available: false, and '{alias}' given every
#          tier role, so each role resolves to that one row.
# Why:     arm P of the spec round 2 probe holds the model tier fixed, so that arm against the
#          single-agent control differs only in whether the work was decomposed.
#
# Comments from the source table are not carried: this is a derived file.
"""


class PinningError(RuntimeError):
    """The requested row cannot carry every role, so the pinned table would be unusable."""


def _rows(table: dict[str, Any]) -> list[dict[str, Any]]:
    rows = table.get("models")
    if not isinstance(rows, list):
        raise PinningError("the policy table has no 'models' list")
    # yaml.safe_load is Any all the way down; this is where the file declares the shape it reads.
    entries = cast("list[Any]", rows)
    return [cast("dict[str, Any]", row) for row in entries if isinstance(row, dict)]


def _roles_in(table: dict[str, Any]) -> list[str]:
    """Every role any row offers, so the pinned row carries the same vocabulary."""
    seen: list[str] = []
    for row in _rows(table):
        for role in row.get("roles", []):
            if isinstance(role, str) and role not in seen:
                seen.append(role)
    return seen


def _target(table: dict[str, Any], alias: str) -> dict[str, Any]:
    for row in _rows(table):
        if row.get("alias") == alias:
            return row
    known = ", ".join(sorted(str(row.get("alias")) for row in _rows(table)))
    raise PinningError(f"no row named {alias!r} in this policy; it has {known}")


def pin_policy(source: Path, dest: Path, *, alias: str) -> Path:
    """Write a copy of ``source`` in which every tier role resolves to the ``alias`` row.

    Args:
        source: The shipped tier policy to derive from.
        dest: Where to write the derived table.
        alias: The model row every role is pinned to.

    Returns:
        ``dest``.

    Raises:
        PinningError: There is no such row, or its executor is one nothing wires.
    """
    table = cast("dict[str, Any]", yaml.safe_load(source.read_text(encoding="utf-8")))
    target = _target(table, alias)
    executor = str(target.get("executor"))
    if executor not in WIRED_EXECUTORS:
        raise PinningError(
            f"row {alias!r} names executor {executor!r}, which nothing wires; a run on it cannot dispatch"
        )

    target["roles"] = _roles_in(table)
    target["available"] = True
    for row in _rows(table):
        if row is not target:
            row["available"] = False

    dest.parent.mkdir(parents=True, exist_ok=True)
    body = yaml.safe_dump(table, sort_keys=False, default_flow_style=False, allow_unicode=True)
    dest.write_text(HEADER.format(source=source, alias=alias) + body, encoding="utf-8")
    # Re-read rather than trust the write: a table this file emitted but the loader refuses is a
    # launch that dies after the seeding, and the only cheap moment to find that out is here.
    yaml.safe_load(dest.read_text(encoding="utf-8"))
    return dest


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="eval_pin_policy", description=__doc__)
    ap.add_argument("source", type=Path)
    ap.add_argument("dest", type=Path)
    ap.add_argument("--alias", default="sonnet", help="the model row every role is pinned to")
    args = ap.parse_args(argv)
    try:
        dest = pin_policy(Path(str(args.source)), Path(str(args.dest)), alias=str(args.alias))
    except PinningError as exc:
        print(f"eval_pin_policy: {exc}", file=sys.stderr)  # noqa: T201 - the refusal must be seen
        return 2
    print(str(dest))  # noqa: T201 - the path IS this script's output
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
